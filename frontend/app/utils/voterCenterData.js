// Helper function to get total centers
export const getTotalCenters = () => voterCenters.length;

// Helper function to get total voters across all centers
export const getTotalVotersInCenters = () => 
    voterCenters.reduce((sum, center) => sum + center.totalVoters, 0);

// Helper function to get total female voters
export const getTotalFemaleVoters = () => 
    voterCenters.reduce((sum, center) => sum + center.availableFemaleVoters, 0);

// Helper function to get total male voters
export const getTotalMaleVoters = () => 
    voterCenters.reduce((sum, center) => sum + center.availableMaleVoters, 0);

// Helper function to get center by ID
export const getCenterById = (id) => 
    voterCenters.find(center => center.id === id);

// Helper function to filter centers by location
export const filterCentersByLocation = (division, district, upazilla) => {
    return voterCenters.filter(center => {
        if (division && center.location.division !== division) return false;
        if (district && center.location.district !== district) return false;
        if (upazilla && center.location.upazilla !== upazilla) return false;
        return true;
    });
};
